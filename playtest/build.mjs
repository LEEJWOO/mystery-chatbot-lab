import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const world=JSON.parse(read('data/world.json'));
const sprites=Object.fromEntries(fs.readdirSync(path.join(root,'assets/npcs')).filter(n=>n.endsWith('.svg')).sort().map(n=>[n.slice(0,-4),read('assets/npcs/'+n).replace(/>\s+</g,'><').trim()]));
const local=Object.fromEntries(Object.entries(sprites).map(([k,v])=>[k,'data:image/svg+xml;base64,'+Buffer.from(v).toString('base64')]));
const data={
 'src/world.generated.mjs':'export const HUB_WORLD = '+JSON.stringify(world)+';\n',
 'src/sprites.generated.mjs':'export const HUB_SPRITES = '+JSON.stringify(sprites)+';\n',
 'src/local-sprites.generated.mjs':'export const MH_LOCAL_SPRITES = '+JSON.stringify(local)+';\n'
};
const core=read('src/core.mjs').replace(/^import .*;\n/gm,'').replace(/^export \{[^\n]+\};?\n?/gm,'');
data['MysteryTestHub.jsx']='// GENERATED by node build.mjs — edit src/core.mjs, src/view.jsx, data/world.json, assets/npcs.\nconst MH_DEMO='+JSON.stringify(world)+';\nconst MH_LOCAL_SPRITES='+JSON.stringify(local)+';\n'+core+'\n'+read('src/view.jsx');
let stale=false;
for(const [p,content] of Object.entries(data)){
 if(process.argv.includes('--check')){if(!fs.existsSync(path.join(root,p))||read(p)!==content){console.error('Generated file differs:',p);stale=true;}}
 else fs.writeFileSync(path.join(root,p),content);
}
if(stale)process.exitCode=1;
else console.log(process.argv.includes('--check')?'Generated files match canonical sources.':'Generated JSX and data modules.');
